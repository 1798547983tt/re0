def canonical(raw: str) -> str:
    raw = raw.strip()
    raw = re.sub(r"（[^）]*(?:回忆|记忆|试炼|遗骸|遗体|远处|外围|被揭示|通讯|远程|观察|后段|死亡结果|下落未明|情报|共感觉|沉睡|大蝎子|借体|领域|不使用死归|不使用多娜狐)[^）]*）", "", raw)
    raw = raw.strip()
    raw = EXTRA.get(raw, raw)
    return ALIASES.get(raw, raw)


