def clean_rank(rank: str) -> str:
    """Keep rank, form and conditions; remove source-quality commentary."""
    rank = re.sub(r"（(?:资料薄|资料不足|存疑|正文战绩有限，推定|军务身份，战绩资料有限|仅战力表，疑似外作污染|身份/形态存疑|权能性质存疑)）", "", rank)
    rank = rank.replace("，推定", "")
